#!/usr/bin/env python3
"""Embed the Ember design's binary assets in the app as C arrays.

usage: python3 tools/embed-assets.py <design folder>

<design folder> is the "TEE-Vanced-Design-Ember" handover package, which is NOT part of this repository.
From it this writes, in the style of the library's own icon font (libs/simple-lib-app/src/ui/icon-data.c):

  apps/yo-player/src/assets/manrope-<weight>.c   Manrope Regular/SemiBold/Bold/ExtraBold (SIL OFL 1.1,
                                                 see apps/yo-player/src/assets/OFL.txt)
  apps/yo-player/src/assets/ember-textures.c     the white helper textures (shape in the alpha channel)

and checks that every source file is what it claims to be (TTF magic, PNG signature). The arrays are opened
at runtime with openFontMemory() and loadGfxTextureMem(); see include/ui-assets.h for the symbols.
Run it again whenever the fonts or textures in the package change, and commit the result.
"""
import pathlib
import struct
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "apps" / "yo-player" / "src" / "assets"

FONTS = [  # (file in schrift/, C symbol)
    ("Manrope-Regular.ttf", "manropeRegularData"),
    ("Manrope-SemiBold.ttf", "manropeSemiBoldData"),
    ("Manrope-Bold.ttf", "manropeBoldData"),
    ("Manrope-ExtraBold.ttf", "manropeExtraBoldData"),
]
TEXTURES = [  # (file in texturen/, C symbol)
    ("rund-r8.png", "texRoundR8Data"),
    ("rund-r16.png", "texRoundR16Data"),
    ("rund-r28.png", "texRoundR28Data"),
    ("ecke-r14.png", "texCornerR14Data"),
    ("ecke-r16.png", "texCornerR16Data"),
    ("ring-r20-w3.png", "texRingR20W3Data"),
    ("ring-r23-w4.png", "texRingR23W4Data"),
    ("ring-r25-w4.png", "texRingR25W4Data"),
    ("ring-r34-w4.png", "texRingR34W4Data"),
    ("schein-r23.png", "texGlowR23Data"),
    ("kreis-64.png", "texCircle64Data"),
]


def c_array(symbol, data):
    lines = []
    for start in range(0, len(data), 12):
        chunk = data[start:start + 12]
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in chunk))
    body = ",\n".join(lines)
    return (f"const unsigned char {symbol}[] = {{\n{body}\n}};\n"
            f"const unsigned int {symbol}Size = sizeof({symbol});\n")


def png_size(data, name):
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        sys.exit(f"{name}: not a PNG")
    width, height, depth, colour = struct.unpack(">IIBB", data[16:26])
    if colour != 6 or depth != 8:
        sys.exit(f"{name}: expected 8-bit RGBA, got depth {depth} colour type {colour}")
    return width, height


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    design = pathlib.Path(sys.argv[1])
    OUT.mkdir(parents=True, exist_ok=True)

    for file_name, symbol in FONTS:
        data = (design / "schrift" / file_name).read_bytes()
        if data[:4] not in (b"\x00\x01\x00\x00", b"true"):
            sys.exit(f"{file_name}: not a TrueType font")
        weight = file_name[len("Manrope-"):-len(".ttf")].lower()
        target = OUT / f"manrope-{weight}.c"
        target.write_text(
            f"// auto-generated by tools/embed-assets.py from {file_name} - do not edit.\n"
            "// Manrope, Copyright 2018 The Manrope Project Authors (https://github.com/googlefonts/manrope),\n"
            "// licensed under the SIL Open Font License 1.1 - see OFL.txt in this folder.\n\n"
            + c_array(symbol, data), encoding="ascii", newline="\n")
        print(f"wrote {target.relative_to(ROOT)} ({len(data)} bytes)")

    parts = ["// auto-generated by tools/embed-assets.py from the Ember handover's texturen/ - do not edit.\n"
             "// White shapes with their form in the alpha channel, tinted when drawn (see src/ui-draw.c).\n"]
    for file_name, symbol in TEXTURES:
        data = (design / "texturen" / file_name).read_bytes()
        width, height = png_size(data, file_name)
        parts.append(f"\n// {file_name}: {width}x{height}\n" + c_array(symbol, data))
        print(f"embedded {file_name} ({width}x{height}, {len(data)} bytes)")
    target = OUT / "ember-textures.c"
    target.write_text("".join(parts), encoding="ascii", newline="\n")
    print(f"wrote {target.relative_to(ROOT)}")

    licence = (design / "schrift" / "OFL.txt").read_bytes()
    (OUT / "OFL.txt").write_bytes(licence)
    print(f"copied OFL.txt ({len(licence)} bytes)")


if __name__ == "__main__":
    main()
